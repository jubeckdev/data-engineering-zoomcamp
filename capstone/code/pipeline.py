"""Monthly Prefect workflow, runnable locally or as an Azure Container Apps Job."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import uuid

os.environ.setdefault("PREFECT_SERVER_ANALYTICS_ENABLED", "false")
os.environ.setdefault("PREFECT_HOME", "/tmp/zoomcamp-prefect")
from prefect import flow, task

from source import extract, ROOT
from transform import transform
from cloud import put, lake, publish_sql, dashboard_data, json_bytes
from render_dashboard import render


@task(retries=2, retry_delay_seconds=5)
def extract_task():
    path, info = extract()
    return str(path), info


@task(retries=2, retry_delay_seconds=5)
def bronze_task(path, info):
    name = f"swiss-rail/source/{info['sha256']}.json"
    put("bronze", name, Path(path).read_bytes())
    downloaded = lake().get_blob_client("bronze", name).download_blob().readall()
    if hashlib.sha256(downloaded).hexdigest() != info["sha256"]:
        raise ValueError("Bronze round-trip checksum mismatch")
    # Transform the lake copy, establishing the actual lake-to-warehouse path.
    lake_copy = ROOT / "runtime/lake-snapshot.json"
    lake_copy.write_bytes(downloaded)
    return str(lake_copy)


@task
def transform_task(path):
    return transform(Path(path))


@task(retries=2, retry_delay_seconds=5)
def publish_task(artifacts, run_id, info):
    for table, item in artifacts.items():
        put(item["layer"], f"swiss-rail/runs/{run_id}/{table}.parquet", Path(item["path"]).read_bytes())
    counts = publish_sql(artifacts, run_id, info["sha256"])
    dashboard = dashboard_data()
    # These derived presentation objects may be regenerated by a task retry;
    # immutable source and Parquet artifacts retain their checksum checks.
    put("gold", f"swiss-rail/runs/{run_id}/dashboard.json", json_bytes(dashboard), overwrite=True)
    put("gold", "swiss-rail/dashboard/current.json", json_bytes(dashboard), overwrite=True)
    (ROOT/"evidence/dashboard-data.json").write_bytes(json_bytes(dashboard))
    html = render(dashboard)
    put("gold", f"swiss-rail/runs/{run_id}/dashboard.html", html, overwrite=True)
    put("gold", "swiss-rail/dashboard/current.html", html, overwrite=True)
    (ROOT/"dashboard/index.html").write_bytes(html)
    return counts


@flow(name="swiss-rail-monthly", log_prints=True)
def pipeline(local=False):
    run_id = str(uuid.uuid4())
    path, info = extract_task()
    if not local:
        path = bronze_task(path, info)
    artifacts = transform_task(path)
    counts = {name:item["rows"] for name,item in artifacts.items()} if local else publish_task(artifacts,run_id,info)
    evidence = dict(run_id=run_id, source=info, destination="local DuckDB" if local else "ADLS Gen2 and Azure SQL", row_counts=counts, status="SUCCESS")
    (ROOT/"evidence/pipeline-run.json").write_bytes(json_bytes(evidence))
    if not local:
        put("gold", f"swiss-rail/runs/{run_id}/verification.json", json_bytes(evidence))
    print(json.dumps(evidence, indent=2))
    return evidence


if __name__ == "__main__":
    parser=argparse.ArgumentParser()
    parser.add_argument("--local", action="store_true")
    pipeline(**vars(parser.parse_args()))
